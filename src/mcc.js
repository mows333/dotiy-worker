export function mccInfo(code) {
  const n = parseInt(code, 10);
  if (!n) return null;
  // Most specific (narrowest) range wins, e.g. 4121 Taxi inside 4011–4131.
  const hits = RANGES.filter(r => n >= r.from && n <= r.to).sort((a, b) => (a.to - a.from) - (b.to - b.from));
  return hits[0] ? { code: String(n).padStart(4, '0'), label: hits[0].label, cat: hits[0].cat, hint: hits[0].hint } : { code: String(n).padStart(4, '0'), label: `MCC ${n}`, cat: null, hint: 'mixed' };
}
